  React.HTMLAttributes<HTMLDivElement>
>(({ className = '', ...props }, ref) => (
  <div
    ref={ref}
    className={`rounded-xl border border-zinc-800 bg-zinc-950 text-zinc-100 shadow-sm ${className}`}
    {...props}
  />
));
Card.displayName = 'Card';

